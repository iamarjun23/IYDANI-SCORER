export function l10n(s) {
  const i = ORDER.indexOf(state.lang);
  return (i >= 0 && STR[s] && STR[s][i]) || s;
}

// Rewrite every tagged element under `root`. Run once at startup and again
// whenever the language changes or a builder writes fresh tagged markup.
export function applyLang(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = l10n(el.dataset.i18n); });
  document.documentElement.lang = state.lang;
}
